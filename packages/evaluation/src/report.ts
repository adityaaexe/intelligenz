/**
 * The Markdown report.
 *
 * A report is a rendering of a results file, never a place to type numbers. Everything
 * below is derived from `RunResult[]`, so a claim in the prose either has a row behind
 * it or is in the limitations section.
 *
 * The mode banner is not decoration. A simulated run measures the harness; quoting its
 * numbers as model capability is the single most likely misuse of this artifact, so the
 * banner is the first thing in the file and the mode is repeated in the aggregate table.
 */

import { RUBRIC_VERSION, RUBRIC_WEIGHTS, rubricTable } from './rubric';
import type { HookControlResult } from './fixture';
import type { Aggregate } from './aggregate';
import type { SkippedRun } from './runner';
import type { RunMode, RunResult } from './types';

export interface ReportInput {
  readonly results: readonly RunResult[];
  readonly skipped: readonly SkippedRun[];
  readonly controls: readonly HookControlResult[];
  readonly aggregate: Aggregate;
  readonly generatedAt: Date;
  readonly suiteFingerprint: string;
  readonly node: string;
}

function fmtDuration(ms: number): string {
  if (ms < 1000) return `${String(ms)}ms`;
  if (ms < 60_000) return `${(ms / 1000).toFixed(2)}s`;
  return `${(ms / 60_000).toFixed(2)}m`;
}

function fmtCost(value: number | null): string {
  return value === null ? 'n/a' : `$${value.toFixed(6)}`;
}

function fmtPct(value: number): string {
  return `${(value * 100).toFixed(1)}%`;
}

function clip(text: string, limit: number): string {
  const single = text.replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
  return single.length <= limit ? single : `${single.slice(0, limit)}…`;
}

function banner(mode: RunMode): string[] {
  if (mode === 'simulated') {
    return [
      '> ## MODE: SIMULATED',
      '>',
      '> Produced by the deterministic benchmark simulator. **No model was contacted.**',
      '> These numbers exercise the harness — judges, rubric, ledger, refusals — and are',
      '> **not evidence of model capability**. They must never be quoted as a real result.',
      '> Every row below carries `mode: simulated`; the aggregator refuses to mix modes.',
    ];
  }

  return [
    '> ## MODE: REAL',
    '>',
    '> Produced against the configured provider. Cost is provider-reported, or `n/a` when',
    '> the provider reported none — it is never estimated. Token counts are what the',
    '> adapter reported, or `n/a`.',
  ];
}

export function renderReport(input: ReportInput): string {
  const { aggregate } = input;
  const mode = aggregate.mode;
  const lines: string[] = [];

  lines.push(`# INTELLIGENZ evaluation — ${input.generatedAt.toISOString()}`, '');
  lines.push(...banner(mode), '');

  lines.push('## Environment', '');
  lines.push('| field | value |', '|---|---|');
  lines.push(`| mode | \`${mode}\` |`);
  lines.push(`| rubric version | \`${RUBRIC_VERSION}\` |`);
  lines.push(`| suite fingerprint | \`${input.suiteFingerprint.split('\n').join(' ')}\` |`);
  lines.push(`| benchmarks | ${String(aggregate.benchmarks)} |`);
  lines.push(`| runs | ${String(aggregate.runs)}${aggregate.skipped > 0 ? ` (+${String(aggregate.skipped)} skipped)` : ''} |`);
  lines.push(`| node | \`${input.node}\` |`);
  lines.push(`| generated by | \`infra/scripts/eval.ts\` |`);
  lines.push('');

  lines.push('## Aggregate', '');
  lines.push('| metric | value | note |', '|---|---|---|');
  lines.push(
    `| completion rate | ${fmtPct(aggregate.completionRate)} | every judge passed, run not disqualified |`,
  );
  lines.push(
    `| verified test pass rate | ${fmtPct(aggregate.verifiedTestPassRate)} | ${String(aggregate.verifiedTestCoverage.runsWithTestJudges)}/${String(aggregate.verifiedTestCoverage.runs)} runs carried a test judge |`,
  );
  lines.push(
    `| security violation rate | ${fmtPct(aggregate.securityViolationRate)} | ${String(aggregate.disqualified)} disqualified |`,
  );
  lines.push(`| mean score | ${aggregate.meanScore.toFixed(2)} | 0–100, rubric ${RUBRIC_VERSION} |`);
  lines.push(
    `| mean cost | ${fmtCost(aggregate.meanCostUsd)} | ${String(aggregate.costCoverage.reported)}/${String(aggregate.costCoverage.runs)} runs reported cost |`,
  );
  lines.push(`| median duration | ${fmtDuration(aggregate.medianDurationMs)} | agent wall clock |`);
  lines.push(`| p95 duration | ${fmtDuration(aggregate.p95DurationMs)} | agent wall clock |`);
  lines.push(
    `| mean retries | ${aggregate.meanRetries === null ? 'n/a' : aggregate.meanRetries.toFixed(3)} | ${String(aggregate.retryCoverage.reported)}/${String(aggregate.retryCoverage.runs)} runs reported a retry count |`,
  );
  lines.push(
    `| resource terminations | ${String(aggregate.resourceTerminations)} | runs killed by wall clock or spend cap |`,
  );
  lines.push('');

  lines.push('## Per benchmark', '');
  lines.push(
    '| benchmark | version | category | score | passed | disq. | duration | cost |',
    '|---|---|---|---:|---|---:|---:|---:|',
  );
  for (const entry of aggregate.perBenchmark) {
    const result = input.results.find((candidate) => candidate.benchmark.id === entry.id);
    const cost = result?.usage.costSource === 'simulated' ? 'n/a (simulated)' : fmtCost(entry.meanCostUsd);
    const cells = [
      `\`${entry.id}\``,
      entry.version,
      entry.category,
      entry.meanScore.toFixed(2),
      `${String(entry.passed)}/${String(entry.runs)}`,
      String(entry.disqualified),
      fmtDuration(entry.meanDurationMs),
      cost,
    ];
    lines.push(`| ${cells.join(' | ')} |`);
  }
  lines.push('');

  lines.push('## What each benchmark proves', '');
  for (const result of input.results) {
    const description = result.benchmark.description;
    lines.push(
      `- **\`${result.benchmark.id}\`** (${result.benchmark.policyExpectation}, ${result.benchmark.category}) — ${
        description === null ? '_no description_' : description
      }`,
    );
  }
  lines.push('');

  lines.push('## Runs', '');
  lines.push(
    '| benchmark | score | passed | disqualified | status | tokens in/out | cost | tools | retries | fixture commit |',
    '|---|---:|---|---:|---|---|---|---:|---:|---|',
  );
  const incomplete = input.results.filter((result) => result.status !== 'succeeded');

  for (const result of input.results) {
    const name = `\`${result.benchmark.id}\``;
    const tokensIn = result.usage.tokensIn === null ? 'n/a' : String(result.usage.tokensIn);
    const tokensOut = result.usage.tokensOut === null ? 'n/a' : String(result.usage.tokensOut);
    const cost =
      result.usage.costSource === 'simulated' ? 'n/a (simulated)' : fmtCost(result.usage.costUsd);
    const retries = result.retries === null ? 'n/a' : String(result.retries);

    const cells = [
      name,
      result.score.toFixed(2),
      result.passed ? 'yes' : 'no',
      result.disqualified ? '**yes**' : 'no',
      result.status === 'succeeded' ? result.status : `${result.status} †`,
      `${tokensIn}/${tokensOut}`,
      cost,
      String(result.toolInvocations),
      retries,
      `\`${result.fixtureCommit.slice(0, 12)}\``,
    ];
    lines.push(`| ${cells.join(' | ')} |`);
  }
  lines.push('');

  if (incomplete.length > 0) {
    lines.push(
      '† The run did not complete. Its score is the arithmetic of the judges over whatever was',
      'left behind — not evidence that the agent did the task, and not a baseline datapoint.',
      '',
    );
  }

  const disqualified = input.results.filter((result) => result.disqualified);
  lines.push('## Security gate', '');
  if (disqualified.length === 0 && input.results.every((result) => result.securityEvents.length === 0)) {
    lines.push('No security events in any run.', '');
  } else {
    for (const result of disqualified) {
      lines.push(
        `- **\`${result.benchmark.id}\`** — score forced to **0** (tests: ${result.judgeResults
          .filter((judge) => judge.dimension === 'testCorrectness')
          .map((judge) => judge.status)
          .join(', ') || 'none'}). Reason: ${result.disqualificationReason ?? 'unknown'}.`,
      );
      for (const event of result.securityEvents) {
        lines.push(`  - \`${event.kind}\` at \`${event.path ?? '(unknown)'}\` — ${event.detail}`);
      }
    }
    lines.push('');
  }

  const failing = input.results.flatMap((result) =>
    result.judgeResults
      .filter((judge) => judge.status !== 'passed')
      .map((judge) => ({ benchmark: result.benchmark.id, judge })),
  );

  lines.push('## Judge detail', '');
  if (failing.length === 0) {
    lines.push('Every judge passed in every run. Per-judge rows are elided when there is nothing to explain.', '');
  } else {
    lines.push('Non-passing judges only — a passing judge says nothing a score does not already say.', '');
    lines.push('| benchmark | # | type | dimension | status | detail |', '|---|---:|---|---|---|---|');
    for (const entry of failing) {
      lines.push(
        `| \`${entry.benchmark}\` | ${String(entry.judge.index)} | ${entry.judge.type} | ${entry.judge.dimension} | ${entry.judge.status} | ${clip(entry.judge.detail, 120)} |`,
      );
    }
    lines.push('');
  }

  if (input.controls.length > 0) {
    lines.push('## Fixture controls', '');
    lines.push('A hostile fixture is only evidence if its hostility is real. Each control below runs the');
    lines.push('fixture’s attack against a throwaway copy and requires it to succeed — which is what makes');
    lines.push('"it did not succeed during the agent run" a measurement rather than a hope.', '');
    lines.push('| benchmark | control | result | detail |', '|---|---|---|---|');
    for (const control of input.controls) {
      lines.push(
        `| \`${control.benchmarkId}\` | ${control.kind} | ${control.fired ? 'fires (live)' : '**did not fire — fixture unusable**'} | ${clip(control.detail, 140)} |`,
      );
    }
    lines.push('');
  }

  if (input.skipped.length > 0) {
    lines.push('## Skipped runs', '');
    for (const skip of input.skipped) {
      lines.push(`- \`${skip.benchmarkId}\`@${skip.benchmarkVersion} run ${String(skip.runIndex)}: ${skip.reason}`);
    }
    lines.push('');
  }

  lines.push('## Rubric', '');
  lines.push(`\`${RUBRIC_VERSION}\` — ${rubricTable()}.`);
  lines.push('');
  lines.push(
    `Total = 100 × earned / applicable, where applicable is the weight of the dimensions a benchmark actually judges. ` +
      `Any security event forces **0** and \`disqualified: true\`, whatever the tests did. ` +
      `Weights are fixed: ${Object.entries(RUBRIC_WEIGHTS)
        .map(([dimension, weight]) => `${dimension}=${String(weight)}`)
        .join(', ')}.`,
  );
  lines.push('');

  lines.push('## What this run does not measure', '');
  const limitations =
    mode === 'simulated'
      ? [
          '**Model capability.** No model ran. The simulated executor applies a scripted effect, so a passing score says the judges accept the intended solution — not that any agent can produce it.',
          '**Cost and latency.** Simulated durations are harness overhead (single-digit milliseconds). Cost is `null` because nothing was billed and nothing was reported.',
          '**Security behaviour.** One benchmark is scripted to violate on purpose, to prove the gate fires. That is a test of the detector, not a finding about a model.',
        ]
      : [
          '**Judge sandboxing.** Judge commands execute on the host with a scrubbed environment, a pinned git identity and a wall-clock timeout — not inside the agent sandbox. A fixture command is therefore trusted code, and fixtures are reviewed as such.',
          '**Network.** Fixtures contain no network access and no install step. No judge attempts to detect egress; egress is the runtime’s control, measured by the Phase 3/4 proofs.',
          '**Statistical power.** One run per benchmark measures variance in nothing. `--runs N` exists so a future baseline can report spread rather than a single draw.',
          '**Host-path isolation.** `host-write` detection observes a marker path on the host. A sandbox with a private `/tmp` would hide the write from the harness even if the hook fired inside it.',
        ];

  for (const limitation of limitations) lines.push(`- ${limitation}`);
  lines.push('');

  lines.push('## Reproducing', '');
  lines.push('```bash');
  lines.push(`npx tsx infra/scripts/eval.ts --benchmark all --mode ${mode} --runs 1`);
  if (mode === 'real') lines.push('# requires AGENT_MODEL and an explicit --cap-usd');
  lines.push('```');
  lines.push('');

  return `${lines.join('\n')}\n`;
}
